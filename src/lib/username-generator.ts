// ─── Generator ───

function randomItem<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

/** Yeni bir kullanıcı adı üret: "AlanRol" */
export function generateUsername(): string {
  return `${randomItem(ALAN)}${randomItem(ROL)}`;
}

function isBrowser(): boolean {
  return typeof window !== "undefined";
}

/** Kullanıcının mevcut adını getir — yoksa üret ve kaydet */
export function getUsername(): string {
  if (!isBrowser()) return generateUsername();
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved) return saved;
  const name = generateUsername();
  localStorage.setItem(STORAGE_KEY, name);
  return name;
}

/** Kullanıcı adını sıfırla (yeni ad üret) */
export function resetUsername(): string {
  if (!isBrowser()) return generateUsername();
  const name = generateUsername();
  localStorage.setItem(STORAGE_KEY, name);
  return name;
}
